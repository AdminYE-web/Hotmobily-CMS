    /*
    |--------------------------------------------------------------------------
    | Calendar Settings
    |--------------------------------------------------------------------------
    */

    const days = [
        '日',
        '月',
        '火',
        '水',
        '木',
        '金',
        '土'
    ];


    /*
    |--------------------------------------------------------------------------
    | Calendar Type
    |--------------------------------------------------------------------------
    |
    | ถ้า $prd_cloth ไม่มีค่า = normal
    | ถ้า $prd_cloth มีค่า    = cloth
    |
    */

    const calendarType =
        @if (!isset($prd_cloth) || $prd_cloth == '')
            'normal';
        @else
            'cloth';
        @endif


    /*
    |--------------------------------------------------------------------------
    | API
    |--------------------------------------------------------------------------
    */

    async function loadHolidays()
    {
        const now = new Date();


        /*
         * Current month first day
         */
        const startDate =
            now.getFullYear()
            + '-'
            + String(
                now.getMonth() + 1
            ).padStart(2, '0')
            + '-01';


        /*
         * Next month last day
         */
        const nextMonthLastDate =
            new Date(
                now.getFullYear(),
                now.getMonth() + 2,
                0
            );


        const endDate =
            nextMonthLastDate.getFullYear()
            + '-'
            + String(
                nextMonthLastDate.getMonth() + 1
            ).padStart(2, '0')
            + '-'
            + String(
                nextMonthLastDate.getDate()
            ).padStart(2, '0');


        /*
         * API URL
         */
        const url =
            '/api/v1/holidays'
            + '?from='
            + encodeURIComponent(startDate)
            + '&to='
            + encodeURIComponent(endDate)
            + '&calendar_type='
            + encodeURIComponent(calendarType);


        /*
         * Request API
         */
        const response =
            await fetch(
                url,
                {
                    method: 'GET',

                    headers: {
                        'Accept': 'application/json'
                    }
                }
            );


        if (!response.ok) {

            throw new Error(
                'Failed to load holidays. HTTP '
                + response.status
            );
        }


        const result =
            await response.json();


        /*
         * Expected:
         *
         * {
         *     success: true,
         *     data: [...]
         * }
         */

        return result.data ?? [];
    }


    /*
    |--------------------------------------------------------------------------
    | Date Formatter
    |--------------------------------------------------------------------------
    */

    function formatDate(
        year,
        month,
        date
    ) {
        return (
            year
            + '-'
            + String(
                month + 1
            ).padStart(2, '0')
            + '-'
            + String(
                date
            ).padStart(2, '0')
        );
    }


    /*
    |--------------------------------------------------------------------------
    | Find Holiday
    |--------------------------------------------------------------------------
    */

    function findHoliday(
        holidays,
        currentDate
    ) {
        return holidays.find(
            holiday =>
                holiday.date === currentDate
        );
    }


    /*
    |--------------------------------------------------------------------------
    | Apply Weekend Color
    |--------------------------------------------------------------------------
    |
    | Sunday   = type1
    | Saturday = type2
    |
    */

    function applyWeekendStyle(
        cell,
        dayOfWeek
    ) {

        /*
         * Sunday
         */
        if (dayOfWeek === 0) {

            cell.classList.add(
                'holiday_type1'
            );

            return;
        }


        /*
         * Saturday
         */
        if (dayOfWeek === 6) {

            cell.classList.add(
                'holiday_type2'
            );
        }
    }


    /*
    |--------------------------------------------------------------------------
    | Apply Holiday From API
    |--------------------------------------------------------------------------
    */

    function applyHolidayStyle(
        cell,
        holiday
    ) {

        if (!holiday) {
            return;
        }


        /*
         * Remove weekend color first
         */
        cell.classList.remove(
            'holiday_type1',
            'holiday_type2',
            'holiday_type3'
        );


        /*
         * API returns:
         *
         * type1
         * type2
         * type3
         */

        const allowedTypes = [
            'type1',
            'type2',
            'type3'
        ];


        if (
            allowedTypes.includes(
                holiday.type
            )
        ) {

            cell.classList.add(
                'holiday_' + holiday.type
            );
        }


        /*
         * Show title on hover
         */
        if (holiday.title) {

            cell.setAttribute(
                'title',
                holiday.title
            );
        }


        /*
         * Useful for debug / future mobile-like UI
         */
        if (holiday.id) {

            cell.dataset.holidayId =
                holiday.id;
        }
    }


    /*
    |--------------------------------------------------------------------------
    | Create Date Cell
    |--------------------------------------------------------------------------
    */

    function createDateCell(
        year,
        month,
        date,
        dayOfWeek,
        holidays
    ) {

        const cell =
            document.createElement('td');


        cell.textContent =
            date;


        /*
         * Weekend
         */
        applyWeekendStyle(
            cell,
            dayOfWeek
        );


        /*
         * YYYY-MM-DD
         */
        const currentDate =
            formatDate(
                year,
                month,
                date
            );


        /*
         * Find API Holiday
         */
        const holiday =
            findHoliday(
                holidays,
                currentDate
            );


        /*
         * API holiday overrides weekend
         */
        applyHolidayStyle(
            cell,
            holiday
        );


        return cell;
    }


    /*
    |--------------------------------------------------------------------------
    | Render Current Month
    |--------------------------------------------------------------------------
    */

    function renderCurrentMonth(
        tableBody,
        holidays,
        year,
        month
    ) {

        const numDays =
            new Date(
                year,
                month + 1,
                0
            ).getDate();


        const firstDay =
            new Date(
                year,
                month,
                1
            ).getDay();


        /*
         * Title
         */
        document
            .getElementById('month')
            .textContent =
                `${month + 1}月 ${year}`;


        let date = 1;


        /*
         * Max 6 rows
         */
        for (
            let week = 0;
            week < 6;
            week++
        ) {

            const row =
                document.createElement(
                    'tr'
                );


            for (
                let day = 0;
                day < 7;
                day++
            ) {

                /*
                 * Empty before first date
                 */
                if (
                    week === 0
                    && day < firstDay
                ) {

                    row.appendChild(
                        document.createElement(
                            'td'
                        )
                    );

                    continue;
                }


                /*
                 * End month
                 */
                if (
                    date > numDays
                ) {

                    row.appendChild(
                        document.createElement(
                            'td'
                        )
                    );

                    continue;
                }


                /*
                 * Date Cell
                 */
                const cell =
                    createDateCell(
                        year,
                        month,
                        date,
                        day,
                        holidays
                    );


                row.appendChild(cell);

                date++;
            }


            tableBody.appendChild(row);


            /*
             * Finish
             */
            if (
                date > numDays
            ) {
                break;
            }
        }
    }


    /*
    |--------------------------------------------------------------------------
    | Render Next Month
    |--------------------------------------------------------------------------
    */

    function renderNextMonth(
        tableBody,
        holidays,
        currentYear,
        currentMonth
    ) {

        /*
         * Determine next month
         */
        const nextMonth =
            currentMonth === 11
                ? 0
                : currentMonth + 1;


        const nextYear =
            currentMonth === 11
                ? currentYear + 1
                : currentYear;


        const numDays =
            new Date(
                nextYear,
                nextMonth + 1,
                0
            ).getDate();


        const firstDay =
            new Date(
                nextYear,
                nextMonth,
                1
            ).getDay();


        /*
        |--------------------------------------------------------------------------
        | Blank Row
        |--------------------------------------------------------------------------
        */

        const blankSpace =
            document.createElement(
                'tr'
            );


        blankSpace.classList.add(
            'blank_space'
        );


        tableBody.appendChild(
            blankSpace
        );


        /*
        |--------------------------------------------------------------------------
        | Month Header
        |--------------------------------------------------------------------------
        */

        const monthRow =
            document.createElement(
                'tr'
            );


        const monthHeader =
            document.createElement(
                'th'
            );


        monthHeader.colSpan =
            7;


        monthHeader.textContent =
            `${nextMonth + 1}月 ${nextYear}`;


        monthHeader.classList.add(
            'calendar_title'
        );


        monthRow.appendChild(
            monthHeader
        );


        tableBody.appendChild(
            monthRow
        );


        /*
        |--------------------------------------------------------------------------
        | Day Header
        |--------------------------------------------------------------------------
        */

        const dayRow =
            document.createElement(
                'tr'
            );


        days.forEach(
            dayName => {

                const th =
                    document.createElement(
                        'th'
                    );


                th.textContent =
                    dayName;


                dayRow.appendChild(
                    th
                );
            }
        );


        tableBody.appendChild(
            dayRow
        );


        /*
        |--------------------------------------------------------------------------
        | Dates
        |--------------------------------------------------------------------------
        */

        let date = 1;


        for (
            let week = 0;
            week < 6;
            week++
        ) {

            const row =
                document.createElement(
                    'tr'
                );


            for (
                let day = 0;
                day < 7;
                day++
            ) {

                /*
                 * Empty before first date
                 */
                if (
                    week === 0
                    && day < firstDay
                ) {

                    row.appendChild(
                        document.createElement(
                            'td'
                        )
                    );

                    continue;
                }


                /*
                 * End month
                 */
                if (
                    date > numDays
                ) {

                    row.appendChild(
                        document.createElement(
                            'td'
                        )
                    );

                    continue;
                }


                /*
                 * Date Cell
                 */
                const cell =
                    createDateCell(
                        nextYear,
                        nextMonth,
                        date,
                        day,
                        holidays
                    );


                row.appendChild(
                    cell
                );


                date++;
            }


            tableBody.appendChild(
                row
            );


            /*
             * Finish
             */
            if (
                date > numDays
            ) {
                break;
            }
        }
    }


    /*
    |--------------------------------------------------------------------------
    | Render Calendar
    |--------------------------------------------------------------------------
    */

    async function renderCalendar()
    {

        const tableBody =
            document.getElementById(
                'dates'
            );


        /*
         * Clear existing
         */
        tableBody.innerHTML = '';


        try {

            /*
             * Get holidays from API
             */
            const holidays =
                await loadHolidays();


            /*
             * Current date
             */
            const now =
                new Date();


            const year =
                now.getFullYear();


            const month =
                now.getMonth();


            /*
             * Current Month
             */
            renderCurrentMonth(
                tableBody,
                holidays,
                year,
                month
            );


            /*
             * Next Month
             */
            renderNextMonth(
                tableBody,
                holidays,
                year,
                month
            );

        } catch (error) {

            console.error(
                'Calendar Error:',
                error
            );


            /*
             * Optional fallback message
             */
            const row =
                document.createElement(
                    'tr'
                );


            const cell =
                document.createElement(
                    'td'
                );


            cell.colSpan = 7;

            cell.textContent =
                'カレンダー情報を取得できませんでした。';


            row.appendChild(
                cell
            );


            tableBody.appendChild(
                row
            );
        }
    }


    /*
    |--------------------------------------------------------------------------
    | Start
    |--------------------------------------------------------------------------
    */

    document.addEventListener(
        'DOMContentLoaded',
        function () {

            renderCalendar();

        }
    );

</script>